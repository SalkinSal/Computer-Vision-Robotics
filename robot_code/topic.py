# topic type, based on where it's being initialized
class TopType(Enum):
    REG = 0   # registry
    PUB = 1   # publisher
    SUB = 2   # subscriber


class Topic:
    # ================================
    #     INIT & CLOSE
    # ================================
    def __init__(self, type:TopType, name:str, config:Struct):
        self.name = name
        self.type = type
        self.config = config

        self.lock = config.lock
        self.bl = config.buffer_length
        self.publisher = config.publisher
        self.subscribers = config.subscribers
        self.dtypes = self.config.dtypes

        
        # --- Initialize message buffer as array in shared memory -----
        # name of the shared memory is the name of the topic
        if self.type == TopType.REG: 
            # create new shared memory first time topic is registered
            size = calculate_memory_size(
                dtype_formats=self.dtypes.formats, 
                bl=self.bl)
            self.shm = SharedMemory(create=True, name=self.name, size=size)
        else:
            # attach to existing shared memory for a publisher or subscriber
            self.shm = SharedMemory(name=self.name)

        # build internal np array using shared memory as the buffer
        self.buffer = np.ndarray( 
            self.bl + 1, # buffer length + head
            dtype=np.dtype(self.config.dtypes),
            buffer=self.shm.buf
        )

        # always initialize local head as 0
        self.head = 0
        if self.type == TopType.PUB:
            # set the head in the array
            self.buffer[0][0] = self.head
    
    def close(self):
        """
        Close the topic by releasing shared memory.

        Unlink the shared memory if the topic is of type Registry.
        """ 
        self.shm.close()

        # unlink if type registry
        if self.type == TopType.REG:
            self.shm.unlink()


    # ================================
    #     PUB/SUB
    # ================================
    def publish(self, timestamp:int, message, pad_arrays:bool=False, casting:bool=True) -> bool:      
        """
        Publish a message to the topic's ring buffer.

        Message must be a list, tuple, or numpy ndarray. The messages validity will be checked.
        If a multidimensional message field (a list or array of lists) has fewer entries
        than defined as maximum in the config pad_arrays needs to be True to avoid an error.
        The user is responsible for ensuring that all elements in a multidimensional message field
        are of the same data type.

        Parameters
        ----------
        timestamp:  int
                    Timestamp generated by the node, needs to be int because message-head is stored in same buffer-column.
        message:    list, tuple, or np.ndarray
                    The message, formatted as defined in the topic config.
        pad_arrays: bool
                    Whether to pad multidimensional message fields with fewer entries than the max defined in the config.
        casting:    bool
                    Whether to allow numpy safe-casting when publishing the message.
        Returns
        -------
        bool
            True if publishing was successful, else False.
        """
        # only the publisher node may publish to a topic
        if self.type != TopType.PUB:
            print(f'[bold][red]Only node [blue]{self.publisher}[/blue] can publish to topic [bright_blue]{self.name}[/bright_blue]!\n'
                  + f"[bold yellow]Continuing to run framework.")
            return False

        # assert data format of message is correct
        message = format_message(
            t_name=self.name,
            timestamp=timestamp,
            dtypes=self.dtypes,
            message=message,
            pad_arrays=pad_arrays,
            casting=casting)
        # message = self.format_message(timestamp, message, pad_arrays)
        if message is None:
            return False
        
        # acquire lock to prevent other processes accessing the buffer simultaneously
        with self.lock:
            # increment writing head so it's pointing to the buffer slot that will be written to
            self.head += 1

            # write the new message
            idx = (self.head - 1) % self.bl + 1 # account for ring buffer
            self.buffer[idx] = message
            
            # update buffer head
            self.buffer[0][0] = self.head
        return True # publishing successful

    def get_msg(self, max_msgs:int=0, new_only:bool=True) -> list:
        """
        Retrieve messages from the topic's ring buffer.

        Either get only new messages if there are any, up to a maximum number
        or get a set number of messages, whether they are new or not.
        In either case, all messages in the topic are marked as read/not new.

        Parameters
        ----------
        max_msgs:   int
                    How many messages to retrieve (starting with the newest). 0 gets all new messages if there are any.
        new_only:   bool
                    Whether to get only new messages or the max number of messages whether already read or not.
                    If new_only is False, max_msgs must not be 0!

        Returns
        -------
        list or None
            List containing one or more messages or None if messages could not be retrieved or there were no new messages.
        """
        # ensure the node isn't trying to retrieve messages from the publisher-topic
        if self.type == TopType.PUB:
            print(f"[bold][red]The publishing node cannot read messages from topic [bright_blue]{self.name}[/bright_blue] directly! "
                  + "Set the node as a subscriber and use [white]read_topic()[/white] instead!\n"
                  + f"[bold yellow]Continuing to run framework.")
            return None

        # check that max_msgs doesn't exceed buffer length
        if max_msgs > self.bl:
            print(f"[bold][white]max_messages {max_msgs}[/white][yellow] exceeds length of the ring buffer for "
                  + f"topic [bright_blue]{self.name}[/bright_blue]! Retrieving [white]{self.bl}[/white] messages instead.")
            max_msgs = self.bl

        msg_head = self.buffer[0][0]
        if new_only:
            # check how many new messages are in the buffer
            no_msgs = msg_head - self.head
            
            # stop if no new messages were received
            if no_msgs == 0:
                return None

        else: # retrieve set number of latest messages
            # assert max_msgs wasn't left at 0
            if max_msgs == 0:
                print(f"[bold][red]Cannot retrieve [white]0[/white] messages from topic [bright_blue]{self.name}"
                      + f"[/bright_blue] if [white]new_only[/white] is [white]{False}[/white]!\n"
                      + f"[bold yellow]Continuing to run framework.")
                      
                return None
            # ensure max_msgs is not larger than the total number of messages
            if max_msgs > msg_head:
                no_msgs = self.head
            else:
                no_msgs = max_msgs

        if no_msgs == 0:
            # this can happen e.g. if new_only=False but no message has been published yet!
            return None
        
        # acquire lock to make sure there is no interference with the publishing node
        with self.lock:
            # update message head to make sure you don't miss any messages that came in
            #   between getting the earlier head value and acquiring the lock 
            new_msg_head = self.buffer[0][0]
            diff = new_msg_head - msg_head

            if new_only:
                # if head has changed, update the number of new messages
                if diff != 0 and new_only:
                    no_msgs += diff
                # reduce number of mesages to stated maximum 
                if max_msgs != 0: # (max==0: get all new msgs)
                    no_msgs = min (no_msgs, max_msgs)
                if no_msgs > self.bl:
                    print(f"[bold][yellow]{diff} older messages on topic [bright_blue]{self.name} "
                          + "[bright_blue]were overwritten and couldn't be retrieved!")
                    no_msgs = self.bl


            # retrieve the specified number of messages
            msg_idx = (new_msg_head - 1) % self.bl + 1
            idx_start =  msg_idx - (no_msgs - 1)
            idx_end = msg_idx + 1

            if idx_start >= 1:
                ret_msgs = self.buffer[idx_start:idx_end].copy() # copy so it's not a view on the buffer that can be overwritten
            # account for buffer's ring structure
            else:
                ret_msgs = np.hstack((self.buffer[(idx_start + self.bl):(self.bl + 1)], self.buffer[1:idx_end])).copy()
                # bl + 2: 1 to account for head at idx 0, 1 because the upper idx is exclusive not inclusive

        # update local head
        self.head = msg_head

        return ret_msgs

    def get_synced_msg(
            self,
            timestamp:int,
            max_distance:int,
            field_name:str="timestamp",
            direction:Literal["newer", "older", "nearest"]="nearest",
            ) -> tuple:
            """
            Retrieve the message closest to a timestamp.

            Calling this function does not influence which messages are marked as read.
            When this function is called through the Node, the default max_distance is DT/2.
            
            Parameters
            ----------
            timestamp : float
                The timestamp to sync messages to.
            max_distance: int
                Maximum distance between timestamp and message in seconds.
            field_name: str
                Name of the message field to sync to. default="timestamp".
            direction : {"older", "newer", "nearest"}, default="nearest"
                Search direction:
                - "older": Closest message at or before the timestamp.
                - "newer": Closest message at or after the timestamp.
                - "nearest": Closest message overall.
            Returns
            -------
            tuple or None
                Message closest to timestamp within given parameters or None if no such message was found.
            """
            if direction not in ["newer", "older", "nearest"]:
                print(f"[bold][red]Cannot get synced message from topic [bright_blue]{self.name}[/bright_blue]! "
                      + f"Invalid direction [white]{direction}[/white].[/red]\n"
                      + "[yellow]Continuing to run framework.")
                return

            # find index of specified field
            try:
                f_idx = self.dtypes.names.index(field_name)
            except ValueError:
                print(f"[bold][red]Cannot get synced message from topic [bright_blue]{self.name}[/bright_blue]"
                      + f" because field [white]{field_name}[/white] does not exist!\n"
                      + "[yellow]Continuing to run framework.")
                return
            
            with self.lock:
                msg_head = self.buffer[0][0]
                if msg_head == 0:
                    # No message published to topic yet.
                    print(f"[bold][red]Can't get synced timestamp from topic [bright_blue]{self.name}"
                          + "[/bright_blue], since no messages have been published to the topic yet.\n"
                          + "[yellow]Continuing to run framework.")
                    return None
                # run binary search to find index of closest message
                msg_idx = self.timestamp_index(timestamp=timestamp, msg_head=msg_head, field_idx=f_idx)

                # find the 
                # account for edge case: one single message published so far
                if msg_idx == 1:
                    prev = None
                else:
                    prev_idx = (msg_idx-2) % self.bl + 1
                    prev = self.buffer[prev_idx]

                next = self.buffer[msg_idx]

            # release lock and check if valid message was found
            if direction == "older":
                # if no older message exists in the buffer, the method exits here
                if prev is None:
                    print(f"[bold][yellow]There are no messages in topic [bright_blue]{self.name}[/bright_blue] "
                          + "older than the target timestamp.")
                    return None
                diff = timestamp - prev[f_idx]
                msg = prev
            elif direction == "newer" or prev is None: # if prev is None, next is closest by default
                diff = next[f_idx] - timestamp
                msg = next
            else: # direction: "nearest"
                diff_p = timestamp - prev[f_idx]
                diff_n = next[f_idx] - timestamp
                if diff_p < diff_n:
                    diff = diff_p
                    msg = prev
                else:
                    diff = diff_n
                    msg = next

            if diff > max_distance:
                print(f"[bold][red]Topic [bright_blue]{self.name}[/bright_blue] has no messages within "
                      + "[white]max_distance[/white] in the given direction of the target timestamp!"
                      + "[yellow]Continuing to run framework.")
                return None
            return msg


    # ================================
    #     AUXILIARY METHODS 
    # ================================
    def timestamp_index(self, timestamp, msg_head:int, field_idx:int=0) -> int:
        """
        Binary search to find the index at which the timestamp would be inserted into the column of the ring buffer.

        The message searches the first message field, the automatic timestamp, by default,
        but can be run on any other message field containing a timestamp of a format
        matching the reference timestamp.
        It accounts for the structure of the ring buffer and the fact that
        the message head is stored at index 0.
        Assumes that at least one message has been published to the buffer 
        and that the timestamps in the buffer are in order.
        
        Parameters
        ----------
        timestamp:  int/float
            The reference timestamp to be inserted.
        msg_head:   int
            Position of message head (idx of last published message).
        field_idx: int
            Index of the message field containing the timestamp to be searched, default=0.

        Returns
        -------
        int
            The insertion index in [1, bl+1].
        """
        n = min(msg_head, self.bl) # account for partially empty buffer
        lo = 1
        hi = n

        while lo < hi:
            mid = (lo + hi) // 2
            physical_idx = (msg_head + mid - 1) % n + 1 # account for 1-based index
            mid_timestamp = self.buffer[physical_idx][field_idx]

            if mid_timestamp < timestamp:
                lo = mid + 1
            else:
                hi = mid

        # convert lo to physical index
        idx = (msg_head + lo - 1) % n + 1
        return idx


    def get_config(self) -> Struct:
        """
        Return the topic's topic config.

        Returns
        -------
        dict or Struct
            The topic config.
        """
        return self.config

    def get_subscribers(self) -> list:
        """
        Return the names of nodes subscribed to the topic.

        Returns
        -------
        list
            Subscribers to the topic.
        """
        return self.subscribers

    def __str__(self):
        return f"Topic {self.name} (pub: {self.publisher}, subs: {self.subscribers})"

    def __repr__(self):
        return f"Topic('{self.name}')"
